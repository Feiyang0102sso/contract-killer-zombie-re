int CMathFixed::Sin(int angle)
{
    const int ANGLE_180 = 180 << 16;
    const int ANGLE_360 = 360 << 16;

    int absolute = angle;
    if (absolute < 0) {
        absolute = -absolute;
    }
    if (absolute >= ANGLE_360) {
        absolute = absolute % ANGLE_360;
    }

    // fold into 0..90 degrees
    int folded = absolute;
    if (absolute > ANGLE_180) {
        folded = ANGLE_360 - absolute;
    }
    if (folded > Degrees_90 && folded <= ANGLE_180) {
        folded = ANGLE_180 - folded;
    }

    int index = (int)(((long long)folded << 16) / 0x1685) >> 16;
    int value = One;
    if (index <= 0x3FE) {
        value = SinLUT[index];
    }
    if (absolute > ANGLE_180) {
        value = -value;
    }
    if (angle >= 0) {
        return value;
    }
    return -value;
}

